-- ============================================================
-- 1. USER SUBMITS A TRANSACTION (deposit / withdraw) -> PENDING
--    id is generated by DB. Forces status='pending'. Rate limited.
-- ============================================================
CREATE OR REPLACE FUNCTION public.submit_transaction(
  p_type TEXT,
  p_amount_ugx NUMERIC,
  p_description TEXT DEFAULT NULL,
  p_payment_method TEXT DEFAULT NULL,
  p_recipient_info TEXT DEFAULT NULL
)
RETURNS public.transactions
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_id TEXT;
  v_uid UUID := auth.uid();
  v_wallet public.wallets;
  v_res public.transactions;
  v_pending_withdrawals NUMERIC := 0;
  v_available_balance NUMERIC := 0;
  v_min_withdrawal NUMERIC := 5000;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;

  -- blocked accounts can't transact
  IF EXISTS (SELECT 1 FROM public.profiles WHERE id = v_uid AND status = 'blocked') THEN
    RAISE EXCEPTION 'Account is blocked';
  END IF;

  IF p_type NOT IN ('deposit', 'withdraw') THEN
    RAISE EXCEPTION 'Invalid transaction type';
  END IF;
  IF p_amount_ugx IS NULL OR p_amount_ugx <= 0 THEN
    RAISE EXCEPTION 'Amount must be greater than zero';
  END IF;

  -- Atomic wallet row lock
  SELECT * INTO v_wallet FROM public.wallets WHERE user_id = v_uid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Wallet not found'; END IF;

  -- Authoritative withdrawal checks: minimum amount and available balance minus pending withdrawals
  IF p_type = 'withdraw' THEN
    SELECT COALESCE(SUM(amount_ugx), 0) INTO v_pending_withdrawals
    FROM public.transactions
    WHERE user_id = v_uid
      AND type = 'withdraw'
      AND status IN ('pending', 'processing');

    v_available_balance := GREATEST(0, v_wallet.total_balance_ugx - v_pending_withdrawals);

    SELECT COALESCE(
      (SELECT numeric_value FROM public.platform_settings WHERE key = 'minimum_withdrawal_amount' LIMIT 1),
      5000
    ) INTO v_min_withdrawal;

    IF p_amount_ugx < v_min_withdrawal THEN
      RAISE EXCEPTION 'Minimum withdrawal amount is UGX %', v_min_withdrawal;
    END IF;

    IF p_amount_ugx > v_available_balance THEN
      RAISE EXCEPTION 'Insufficient balance: requested UGX %, available withdrawable balance is UGX %',
        p_amount_ugx, v_available_balance;
    END IF;
  END IF;

  v_id := 'tx_' || lower(substring(replace(gen_random_uuid()::text, '-', '') from 1 for 18));

  INSERT INTO public.transactions (
    id, user_id, type, amount_ugx, currency, status,
    description, payment_method, recipient_info, timestamp, created_at
  ) VALUES (
    v_id, v_uid, p_type, p_amount_ugx, 'UGX', 'pending',
    COALESCE(p_description, p_type || ' Request — UGX ' || p_amount_ugx::text),
    p_payment_method, p_recipient_info,
    now(),
    now()
  ) RETURNING * INTO v_res;

  -- Also insert into admin_tasks for visibility in Admin multisig queue
  INSERT INTO public.admin_tasks (
    id, user_id, transaction_id, title, description,
    priority, category, type, status, amount_ugx, created_at
  ) VALUES (
    'task_' || lower(substring(replace(gen_random_uuid()::text, '-', '') from 1 for 18)),
    v_uid, v_id,
    CASE WHEN p_type = 'deposit' THEN 'Deposit Verification: UGX ' || p_amount_ugx::text ELSE 'Withdrawal Review: UGX ' || p_amount_ugx::text END,
    'User requested ' || p_type || ' of UGX ' || p_amount_ugx::text || COALESCE(' via ' || p_payment_method, ''),
    'high',
    CASE WHEN p_type = 'deposit' THEN 'Deposit Verification' ELSE 'Withdrawal Review' END,
    p_type, 'pending', p_amount_ugx, now()
  ) ON CONFLICT DO NOTHING;

  RETURN v_res;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.submit_transaction(TEXT, NUMERIC, TEXT, TEXT, TEXT) FROM anon, public;
GRANT EXECUTE ON FUNCTION public.submit_transaction(TEXT, NUMERIC, TEXT, TEXT, TEXT) TO authenticated;

